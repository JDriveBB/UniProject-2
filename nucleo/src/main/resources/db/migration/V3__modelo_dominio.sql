-- 2. Configuración académica.
CREATE TABLE proyecto (
    id_proyecto   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_docente    bigint        NOT NULL REFERENCES usuario (id_usuario),
    nombre        varchar(150)  NOT NULL,
    descripcion   varchar(2000) NULL,
    fecha_inicio  date          NOT NULL,
    fecha_fin     date          NOT NULL,
    usa_monitores boolean       NOT NULL DEFAULT false,
    CONSTRAINT proyecto_fechas_ck CHECK (fecha_fin >= fecha_inicio)
);
CREATE INDEX proyecto_docente_idx ON proyecto (id_docente);

CREATE TABLE monitor_proyecto (
    id_proyecto bigint NOT NULL REFERENCES proyecto (id_proyecto) ON DELETE CASCADE,
    id_monitor  bigint NOT NULL REFERENCES usuario (id_usuario),
    CONSTRAINT monitor_proyecto_pk PRIMARY KEY (id_proyecto, id_monitor)
);
CREATE INDEX monitor_proyecto_monitor_idx ON monitor_proyecto (id_monitor);

CREATE TABLE equipo (
    id_equipo     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_proyecto   bigint       NOT NULL REFERENCES proyecto (id_proyecto),
    nombre_equipo varchar(100) NOT NULL,
    CONSTRAINT equipo_nombre_uk UNIQUE (id_proyecto, nombre_equipo)
);

CREATE TABLE miembro_equipo (
    id_equipo     bigint      NOT NULL REFERENCES equipo (id_equipo) ON DELETE CASCADE,
    id_usuario    bigint      NOT NULL REFERENCES usuario (id_usuario),
    rol_equipo    varchar(10) NOT NULL DEFAULT 'INTEGRANTE',
    fecha_ingreso timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT miembro_equipo_pk PRIMARY KEY (id_equipo, id_usuario),
    CONSTRAINT miembro_equipo_rol_ck CHECK (rol_equipo IN ('LIDER', 'INTEGRANTE'))
);
CREATE INDEX miembro_equipo_usuario_idx ON miembro_equipo (id_usuario);
-- Supuesto 2 de entrega1: un único líder por equipo.
CREATE UNIQUE INDEX miembro_equipo_un_lider_uk ON miembro_equipo (id_equipo) WHERE rol_equipo = 'LIDER';

CREATE TABLE hito (
    id_hito                       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_proyecto                   bigint        NOT NULL REFERENCES proyecto (id_proyecto),
    nombre_hito                   varchar(150)  NOT NULL,
    descripcion                   varchar(2000) NULL,
    orden                         integer       NOT NULL,
    fecha_inicio                  date          NOT NULL,
    fecha_limite                  date          NOT NULL,
    dias_inactividad_alerta       integer       NOT NULL DEFAULT 3,
    notificar_docente_inactividad boolean       NOT NULL DEFAULT false,
    CONSTRAINT hito_orden_uk UNIQUE (id_proyecto, orden),
    CONSTRAINT hito_orden_ck CHECK (orden >= 1),
    CONSTRAINT hito_fechas_ck CHECK (fecha_limite >= fecha_inicio),
    CONSTRAINT hito_inactividad_ck CHECK (dias_inactividad_alerta BETWEEN 1 AND 60)
);
COMMENT ON COLUMN hito.fecha_limite IS
    'Vence al terminar ese día en America/Bogota. Antes, la nota es provisional (RF8, decisión E1).';

CREATE TABLE criterio_rubrica (
    id_criterio     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_hito         bigint       NOT NULL REFERENCES hito (id_hito) ON DELETE CASCADE,
    descripcion     varchar(500) NOT NULL,
    peso_porcentaje numeric(5,2) NOT NULL,
    puntaje_maximo  numeric(5,2) NOT NULL,
    CONSTRAINT criterio_rubrica_peso_ck CHECK (peso_porcentaje > 0 AND peso_porcentaje <= 100),
    CONSTRAINT criterio_rubrica_puntaje_ck CHECK (puntaje_maximo > 0)
);
CREATE INDEX criterio_rubrica_hito_idx ON criterio_rubrica (id_hito);

-- 3. Ejecución y dependencias.
CREATE TABLE hito_equipo (
    id_hito_equipo bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_hito        bigint      NOT NULL REFERENCES hito (id_hito),
    id_equipo      bigint      NOT NULL REFERENCES equipo (id_equipo),
    estado         varchar(10) NOT NULL DEFAULT 'EN_CURSO',
    CONSTRAINT hito_equipo_uk UNIQUE (id_hito, id_equipo),
    CONSTRAINT hito_equipo_estado_ck CHECK (estado IN ('EN_CURSO', 'ENVIADO', 'EVALUADO'))
);
CREATE INDEX hito_equipo_equipo_idx ON hito_equipo (id_equipo);
COMMENT ON TABLE hito_equipo IS
    'Hito de un equipo. Su id es el que llevan los eventos (Referencia hito) y las rutas /hitos/{id}/evaluar y /hitos/{id}/evaluacion (decisión R-7).';

CREATE TABLE envio_hito (
    id_envio         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_hito_equipo   bigint      NOT NULL REFERENCES hito_equipo (id_hito_equipo),
    id_usuario_envia bigint      NOT NULL REFERENCES usuario (id_usuario),
    fecha_envio      timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX envio_hito_hito_equipo_idx ON envio_hito (id_hito_equipo);

CREATE TABLE tarea (
    id_tarea                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_hito_equipo            bigint        NOT NULL REFERENCES hito_equipo (id_hito_equipo),
    id_encargado              bigint        NULL REFERENCES usuario (id_usuario),
    id_tarea_origen           bigint        NULL REFERENCES tarea (id_tarea),
    titulo                    varchar(150)  NOT NULL,
    descripcion               varchar(2000) NULL,
    estado                    varchar(15)   NOT NULL DEFAULT 'PENDIENTE',
    fecha_cambio_estado       timestamptz   NOT NULL DEFAULT now(),
    bloqueada_por_dependencia boolean       NOT NULL DEFAULT false,
    fecha_bloqueo             timestamptz   NULL,
    edicion_habilitada        boolean       NOT NULL DEFAULT true,
    porcentaje_avance         integer       NOT NULL DEFAULT 0,
    horas_estimadas           numeric(6,2)  NOT NULL,
    fecha_limite              date          NULL,
    fecha_completada          timestamptz   NULL,
    es_prerrequisito_critico  boolean       NOT NULL DEFAULT false,
    en_ruta_critica           boolean       NOT NULL DEFAULT false,
    holgura_horas             numeric(8,2)  NULL,
    nivel_riesgo              varchar(5)    NULL,
    peso                      numeric(6,2)  NULL,
    CONSTRAINT tarea_estado_ck CHECK (estado IN ('PENDIENTE', 'EN_PROGRESO', 'COMPLETADA')),
    CONSTRAINT tarea_avance_ck CHECK (porcentaje_avance BETWEEN 0 AND 100),
    CONSTRAINT tarea_completada_ck CHECK ((estado = 'COMPLETADA') = (porcentaje_avance = 100)
                                      AND (estado = 'COMPLETADA') = (fecha_completada IS NOT NULL)),
    CONSTRAINT tarea_bloqueo_ck CHECK (bloqueada_por_dependencia = (fecha_bloqueo IS NOT NULL)),
    CONSTRAINT tarea_horas_ck CHECK (horas_estimadas > 0),
    CONSTRAINT tarea_origen_ck CHECK (id_tarea_origen <> id_tarea),
    CONSTRAINT tarea_nivel_riesgo_ck CHECK (nivel_riesgo IN ('BAJO', 'MEDIO', 'ALTO')),
    CONSTRAINT tarea_peso_ck CHECK (peso > 0)
);
CREATE INDEX tarea_hito_equipo_idx ON tarea (id_hito_equipo);
CREATE INDEX tarea_encargado_idx ON tarea (id_encargado);
COMMENT ON COLUMN tarea.fecha_limite IS
    'Opcional; si es nula manda la del hito. Vence al terminar el día (America/Bogota).';
COMMENT ON COLUMN tarea.fecha_bloqueo IS
    'Desde cuándo está bloqueada por un prerrequisito incompleto (panel RF10: más de 48 h).';
COMMENT ON COLUMN tarea.holgura_horas IS
    'Último cálculo del motor de dependencias (RF3/RF9), igual que en_ruta_critica y nivel_riesgo.';
COMMENT ON COLUMN tarea.peso IS
    'Peso relativo opcional. El ICE usa horas_estimadas (decisión C1); hoy queda nulo.';

CREATE TABLE dependencia_tarea (
    id_tarea_predecesora bigint NOT NULL REFERENCES tarea (id_tarea) ON DELETE CASCADE,
    id_tarea_dependiente bigint NOT NULL REFERENCES tarea (id_tarea) ON DELETE CASCADE,
    CONSTRAINT dependencia_tarea_pk PRIMARY KEY (id_tarea_predecesora, id_tarea_dependiente),
    CONSTRAINT dependencia_tarea_distintas_ck CHECK (id_tarea_predecesora <> id_tarea_dependiente)
);
CREATE INDEX dependencia_tarea_dependiente_idx ON dependencia_tarea (id_tarea_dependiente);
COMMENT ON TABLE dependencia_tarea IS
    'La predecesora bloquea a la dependiente (RF2). Sin ciclos: lo valida MotorDependencias antes de guardar (4d, R3).';

CREATE TABLE registro_avance (
    id_registro       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_tarea          bigint       NOT NULL REFERENCES tarea (id_tarea),
    id_usuario        bigint       NOT NULL REFERENCES usuario (id_usuario),
    fecha_hora        timestamptz  NOT NULL DEFAULT now(),
    porcentaje_avance integer      NOT NULL,
    observacion       varchar(500) NULL,
    CONSTRAINT registro_avance_porcentaje_ck CHECK (porcentaje_avance BETWEEN 0 AND 100)
);
CREATE INDEX registro_avance_tarea_idx ON registro_avance (id_tarea, fecha_hora);
CREATE INDEX registro_avance_usuario_idx ON registro_avance (id_usuario, fecha_hora);

CREATE TABLE evidencia (
    id_evidencia   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_tarea       bigint        NOT NULL REFERENCES tarea (id_tarea),
    id_usuario     bigint        NOT NULL REFERENCES usuario (id_usuario),
    tipo_evidencia varchar(6)    NOT NULL,
    url            varchar(2048) NOT NULL,
    nombre_archivo varchar(255)  NULL,
    fecha_subida   timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT evidencia_tipo_ck CHECK (tipo_evidencia IN ('PDF', 'IMAGEN', 'ENLACE')),
    CONSTRAINT evidencia_forma_ck CHECK (
        (tipo_evidencia = 'ENLACE' AND url ~ '^https?://' AND nombre_archivo IS NULL)
        OR (tipo_evidencia = 'PDF' AND url ~ '^evidencias/[0-9a-f-]{36}\.pdf$' AND nombre_archivo IS NOT NULL)
        OR (tipo_evidencia = 'IMAGEN' AND url ~ '^evidencias/[0-9a-f-]{36}\.(png|jpg)$' AND nombre_archivo IS NOT NULL))
);
CREATE INDEX evidencia_tarea_idx ON evidencia (id_tarea);
CREATE INDEX evidencia_usuario_idx ON evidencia (id_usuario, fecha_subida);
COMMENT ON COLUMN evidencia.url IS
    'ENLACE: URL http(s). PDF/IMAGEN: clave del archivo en el volumen de evidencias (evidencias/<uuid>.<ext>); se descarga por la API con permisos (restricción 5, R-14).';

CREATE TABLE comentario_tarea (
    id_comentario bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_tarea      bigint        NOT NULL REFERENCES tarea (id_tarea),
    id_autor      bigint        NOT NULL REFERENCES usuario (id_usuario),
    contenido     varchar(2000) NOT NULL,
    fecha_hora    timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT comentario_tarea_contenido_ck CHECK (btrim(contenido) <> '')
);
CREATE INDEX comentario_tarea_tarea_idx ON comentario_tarea (id_tarea, fecha_hora);

CREATE TABLE solicitud_correccion (
    id_solicitud    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_tarea        bigint        NOT NULL REFERENCES tarea (id_tarea),
    id_evidencia    bigint        NOT NULL REFERENCES evidencia (id_evidencia),
    id_lider        bigint        NOT NULL REFERENCES usuario (id_usuario),
    id_estudiante   bigint        NOT NULL REFERENCES usuario (id_usuario),
    observaciones   varchar(2000) NOT NULL,
    estado          varchar(9)    NOT NULL DEFAULT 'PENDIENTE',
    fecha_solicitud timestamptz   NOT NULL DEFAULT now(),
    fecha_atencion  timestamptz   NULL,
    CONSTRAINT solicitud_correccion_estado_ck CHECK (estado IN ('PENDIENTE', 'ATENDIDA')),
    CONSTRAINT solicitud_correccion_atencion_ck CHECK ((estado = 'ATENDIDA') = (fecha_atencion IS NOT NULL))
);
CREATE INDEX solicitud_correccion_tarea_idx ON solicitud_correccion (id_tarea);

