-- 6. Trazabilidad: log de auditoría de solo inserción (restricción 4e).
CREATE TABLE log_auditoria (
    id_log               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario_accion    bigint        NULL REFERENCES usuario (id_usuario),
    entidad_afectada     varchar(40)   NOT NULL,
    id_registro_afectado bigint        NULL,
    accion               varchar(40)   NOT NULL,
    campo_modificado     varchar(60)   NULL,
    valor_anterior       varchar(1000) NULL,
    valor_nuevo          varchar(1000) NULL,
    fecha_hora           timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT log_auditoria_entidad_ck CHECK (entidad_afectada ~ '^[a-z_]{2,40}$'),
    CONSTRAINT log_auditoria_accion_ck CHECK (accion ~ '^[A-Z_]{3,40}$')
);
CREATE INDEX log_auditoria_registro_idx ON log_auditoria (entidad_afectada, id_registro_afectado, fecha_hora);
CREATE INDEX log_auditoria_usuario_idx ON log_auditoria (id_usuario_accion, fecha_hora);
COMMENT ON TABLE log_auditoria IS
    'Solo inserción (4e), protegido por trigger. Sin contraseñas, tokens, códigos ni chat_id (Ley 1581).';

-- T1: el rol de la aplicación es dueño de la tabla, así que REVOKE no la protege; el trigger sí.
CREATE FUNCTION log_auditoria_solo_insercion() RETURNS trigger
    LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'log_auditoria es de solo inserción (restricción 4e)'
        USING ERRCODE = 'restrict_violation';
END;
$$;

CREATE TRIGGER log_auditoria_sin_cambios
    BEFORE UPDATE OR DELETE ON log_auditoria
    FOR EACH ROW EXECUTE FUNCTION log_auditoria_solo_insercion();

CREATE TRIGGER log_auditoria_sin_vaciado
    BEFORE TRUNCATE ON log_auditoria
    FOR EACH STATEMENT EXECUTE FUNCTION log_auditoria_solo_insercion();

