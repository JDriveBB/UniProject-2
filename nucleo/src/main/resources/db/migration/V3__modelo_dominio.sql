CREATE TABLE correo_habilitado (
    id_correo_habilitado  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_proyecto           bigint       NULL REFERENCES proyecto (id_proyecto),
    email                 varchar(254) NOT NULL,
    rol_plataforma        varchar(15)  NOT NULL,
    id_habilitado_por     bigint       NOT NULL REFERENCES usuario (id_usuario),
    fecha_habilitacion    timestamptz  NOT NULL DEFAULT now(),
    id_usuario_registrado bigint       NULL REFERENCES usuario (id_usuario),
    fecha_uso             timestamptz  NULL,
    CONSTRAINT correo_habilitado_uk UNIQUE NULLS NOT DISTINCT (email, id_proyecto),
    CONSTRAINT correo_habilitado_email_ck CHECK (email = lower(email) AND email LIKE '_%@_%'),
    CONSTRAINT correo_habilitado_rol_ck CHECK (rol_plataforma IN ('DOCENTE', 'ESTUDIANTE', 'MONITOR')),
    CONSTRAINT correo_habilitado_proyecto_ck CHECK ((rol_plataforma = 'DOCENTE') = (id_proyecto IS NULL)),
    CONSTRAINT correo_habilitado_uso_ck CHECK ((id_usuario_registrado IS NULL) = (fecha_uso IS NULL))
