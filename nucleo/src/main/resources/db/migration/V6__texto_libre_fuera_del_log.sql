-- V6: bloque 29 ("27b"; decisión del usuario 2026-11-05; Ley 1581 de 2012). El texto libre escrito por personas
-- sale de log_auditoria (inmutable, restricción 4e) a tablas que la supresión del titular puede borrar.
-- El log queda solo con hechos: acción, entidad, id, campo y valores que no son texto de personas.

-- 1. Solicitud de apoyo (decisión 29-2). mensaje NULL = su autor suprimió la cuenta.
--    id_log_origen solo sirve a esta migración y se borra al final.
CREATE TABLE solicitud_apoyo (
    id_solicitud_apoyo bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_tarea           bigint       NOT NULL REFERENCES tarea (id_tarea),
    id_solicitante     bigint       NOT NULL REFERENCES usuario (id_usuario),
    mensaje            varchar(500) NULL,
    fecha_hora         timestamptz  NOT NULL DEFAULT now(),
    id_log_origen      bigint       NULL,
    CONSTRAINT solicitud_apoyo_mensaje_ck CHECK (mensaje IS NULL OR btrim(mensaje) <> '')
);
CREATE INDEX solicitud_apoyo_tarea_idx ON solicitud_apoyo (id_tarea, fecha_hora);
CREATE INDEX solicitud_apoyo_solicitante_idx ON solicitud_apoyo (id_solicitante);
COMMENT ON TABLE solicitud_apoyo IS
    'Solicitud de apoyo del encargado de una tarea (decisiones 18-6 y 29-2). El log guarda solo el hecho (campo solicitud_apoyo = id). mensaje NULL: su autor suprimió la cuenta (Ley 1581).';

-- 2. Anexo de texto libre del log (decisión 29-3): misma clave que la fila del log.
CREATE TABLE texto_auditoria (
    id_log         bigint        PRIMARY KEY REFERENCES log_auditoria (id_log),
    valor_anterior varchar(1000) NULL,
    valor_nuevo    varchar(1000) NULL,
    CONSTRAINT texto_auditoria_valor_ck CHECK (valor_anterior IS NOT NULL OR valor_nuevo IS NOT NULL)
);
COMMENT ON TABLE texto_auditoria IS
    'Texto libre escrito por personas (motivos, títulos, nombres, descripciones) de una fila de log_auditoria, que queda con el campo y sin valores. Se borra cuando su autor suprime la cuenta (Ley 1581, decisión 29-4).';

-- 3. Lo que ya estaba en el log (decisión 29-5). Textos de cuentas ya anonimizadas: no se copian.
INSERT INTO solicitud_apoyo (id_tarea, id_solicitante, mensaje, fecha_hora, id_log_origen)
SELECT l.id_registro_afectado,
       l.id_usuario_accion,
       CASE WHEN u.fecha_anonimizacion IS NULL AND btrim(coalesce(l.valor_nuevo, '')) <> ''
            THEN left(l.valor_nuevo, 500) END,
       l.fecha_hora,
       l.id_log
  FROM log_auditoria l
  JOIN usuario u ON u.id_usuario = l.id_usuario_accion
  JOIN tarea t ON t.id_tarea = l.id_registro_afectado
 WHERE l.accion = 'SOLICITAR_APOYO' AND l.entidad_afectada = 'tarea'
 ORDER BY l.id_log;

INSERT INTO texto_auditoria (id_log, valor_anterior, valor_nuevo)
SELECT l.id_log, l.valor_anterior, l.valor_nuevo
  FROM log_auditoria l
  LEFT JOIN usuario u ON u.id_usuario = l.id_usuario_accion
 WHERE ((l.accion = 'REASIGNAR_TAREA' AND l.campo_modificado = 'motivo')
        OR (l.accion = 'ACTUALIZAR' AND (l.entidad_afectada, l.campo_modificado) IN (
            ('tarea', 'titulo'), ('tarea', 'descripcion'), ('proyecto', 'nombre'), ('proyecto', 'descripcion'),
            ('hito', 'nombre_hito'), ('hito', 'descripcion'), ('criterio_rubrica', 'descripcion'))))
   AND (l.valor_anterior IS NOT NULL OR l.valor_nuevo IS NOT NULL)
   AND u.fecha_anonimizacion IS NULL;

-- Única escritura sobre el log fuera de un INSERT: dentro de la transacción de Flyway (si algo falla, el trigger
-- vuelve a quedar activo). El trigger de vaciado no se toca.
ALTER TABLE log_auditoria DISABLE TRIGGER log_auditoria_sin_cambios;

UPDATE log_auditoria l
   SET campo_modificado = 'solicitud_apoyo',
       valor_anterior = NULL,
       valor_nuevo = (SELECT CAST(s.id_solicitud_apoyo AS varchar(1000))
                        FROM solicitud_apoyo s
                       WHERE s.id_log_origen = l.id_log)
 WHERE l.accion = 'SOLICITAR_APOYO';

UPDATE log_auditoria l
   SET valor_anterior = NULL,
       valor_nuevo = NULL
 WHERE (l.accion = 'REASIGNAR_TAREA' AND l.campo_modificado = 'motivo')
    OR (l.accion = 'ACTUALIZAR' AND (l.entidad_afectada, l.campo_modificado) IN (
        ('tarea', 'titulo'), ('tarea', 'descripcion'), ('proyecto', 'nombre'), ('proyecto', 'descripcion'),
        ('hito', 'nombre_hito'), ('hito', 'descripcion'), ('criterio_rubrica', 'descripcion')));

ALTER TABLE log_auditoria ENABLE TRIGGER log_auditoria_sin_cambios;

ALTER TABLE solicitud_apoyo DROP COLUMN id_log_origen;
