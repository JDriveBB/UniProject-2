-- V11: cursos (única vía de entrada del estudiante), participantes por proyecto, columnas de equipos con cupo y
-- votación de líder. Se aplica sobre bases vacías (decisión del usuario del 2026-11-25): no migra datos viejos.

CREATE TABLE curso (
    id_curso     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_docente   bigint        NOT NULL REFERENCES usuario (id_usuario),
    nombre       varchar(150)  NOT NULL,
    periodo      varchar(20)   NOT NULL,
    descripcion  varchar(2000) NULL,
    archivado_en timestamptz   NULL,
    creado_en    timestamptz   NOT NULL DEFAULT now()
);

CREATE INDEX curso_docente_idx ON curso (id_docente);
CREATE UNIQUE INDEX curso_nombre_uk ON curso (id_docente, lower(nombre), lower(periodo));

COMMENT ON TABLE curso IS 'Curso académico administrado por un docente; única vía de entrada de estudiantes.';
COMMENT ON COLUMN curso.id_curso IS 'Identificador del curso.';
COMMENT ON COLUMN curso.id_docente IS 'Docente dueño del curso.';
COMMENT ON COLUMN curso.nombre IS 'Nombre del curso (único por docente y periodo, sin distinguir mayúsculas).';
COMMENT ON COLUMN curso.periodo IS 'Periodo académico del curso (p. ej. 2026-2).';
COMMENT ON COLUMN curso.descripcion IS 'Descripción opcional del curso.';
COMMENT ON COLUMN curso.archivado_en IS 'Fecha de archivado; NULL si el curso está activo.';
COMMENT ON COLUMN curso.creado_en IS 'Fecha de creación del curso.';

CREATE TABLE miembro_curso (
    id_curso      bigint      NOT NULL REFERENCES curso (id_curso) ON DELETE CASCADE,
    id_usuario    bigint      NOT NULL REFERENCES usuario (id_usuario),
    fecha_ingreso timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (id_curso, id_usuario)
);

CREATE INDEX miembro_curso_usuario_idx ON miembro_curso (id_usuario);

COMMENT ON TABLE miembro_curso IS 'Estudiantes inscritos en un curso.';
COMMENT ON COLUMN miembro_curso.id_curso IS 'Curso al que pertenece el estudiante.';
COMMENT ON COLUMN miembro_curso.id_usuario IS 'Usuario estudiante miembro del curso.';
COMMENT ON COLUMN miembro_curso.fecha_ingreso IS 'Instante en que el estudiante ingresó al curso.';

CREATE TABLE curso_proyecto (
    id_curso    bigint NOT NULL REFERENCES curso (id_curso),
    id_proyecto bigint NOT NULL REFERENCES proyecto (id_proyecto) ON DELETE CASCADE,
    PRIMARY KEY (id_curso, id_proyecto)
);

CREATE INDEX curso_proyecto_proyecto_idx ON curso_proyecto (id_proyecto);

COMMENT ON TABLE curso_proyecto IS 'Cursos asignados a un proyecto académico.';
COMMENT ON COLUMN curso_proyecto.id_curso IS 'Curso asignado (sin cascada: impide borrar cursos en uso).';
COMMENT ON COLUMN curso_proyecto.id_proyecto IS 'Proyecto que recibe los estudiantes del curso.';

CREATE TABLE participante_proyecto (
    id_proyecto bigint NOT NULL REFERENCES proyecto (id_proyecto) ON DELETE CASCADE,
    id_usuario  bigint NOT NULL REFERENCES usuario (id_usuario),
    id_curso    bigint NOT NULL REFERENCES curso (id_curso),
    PRIMARY KEY (id_proyecto, id_usuario)
);

CREATE INDEX participante_proyecto_usuario_idx ON participante_proyecto (id_usuario);
CREATE INDEX participante_proyecto_curso_idx ON participante_proyecto (id_curso);

COMMENT ON TABLE participante_proyecto IS 'Fuente de verdad de los estudiantes que participan en un proyecto y con qué curso cuentan.';
COMMENT ON COLUMN participante_proyecto.id_proyecto IS 'Proyecto en el que participa el estudiante.';
COMMENT ON COLUMN participante_proyecto.id_usuario IS 'Estudiante participante.';
COMMENT ON COLUMN participante_proyecto.id_curso IS 'Curso con el que cuenta el estudiante en el proyecto.';

CREATE TABLE ronda_lider (
    id_ronda         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_equipo        bigint      NOT NULL REFERENCES equipo (id_equipo) ON DELETE CASCADE,
    origen           varchar(10) NOT NULL CONSTRAINT ronda_lider_origen_ck CHECK (origen IN ('PROGRAMADA', 'DEMANDA')),
    abre_en          timestamptz NOT NULL,
    cierra_en        timestamptz NOT NULL,
    cerrada_en       timestamptz NULL,
    resultado        varchar(15) NULL CONSTRAINT ronda_lider_resultado_ck
        CHECK (resultado IN ('LIDER_ELEGIDO', 'EMPATE', 'SIN_VOTOS', 'CANCELADA')),
    id_lider_elegido bigint      NULL REFERENCES usuario (id_usuario),
    CONSTRAINT ronda_lider_fechas_ck CHECK (cierra_en > abre_en),
    CONSTRAINT ronda_lider_cierre_ck CHECK ((cerrada_en IS NULL) = (resultado IS NULL))
);

CREATE UNIQUE INDEX ronda_lider_abierta_uk ON ronda_lider (id_equipo) WHERE cerrada_en IS NULL;

COMMENT ON TABLE ronda_lider IS 'Rondas de votación para elegir al líder de un equipo (bloque 3).';
COMMENT ON COLUMN ronda_lider.id_ronda IS 'Identificador de la ronda de votación.';
COMMENT ON COLUMN ronda_lider.id_equipo IS 'Equipo que elige líder.';
COMMENT ON COLUMN ronda_lider.origen IS 'Cómo se abrió la ronda: PROGRAMADA o DEMANDA.';
COMMENT ON COLUMN ronda_lider.abre_en IS 'Instante de apertura de la ronda.';
COMMENT ON COLUMN ronda_lider.cierra_en IS 'Instante límite de cierre de la ronda.';
COMMENT ON COLUMN ronda_lider.cerrada_en IS 'Instante efectivo de cierre; NULL mientras la ronda sigue abierta.';
COMMENT ON COLUMN ronda_lider.resultado IS 'Resultado al cerrar: LIDER_ELEGIDO, EMPATE, SIN_VOTOS o CANCELADA.';
COMMENT ON COLUMN ronda_lider.id_lider_elegido IS 'Usuario elegido como líder cuando el resultado es LIDER_ELEGIDO.';

CREATE TABLE voto_lider (
    id_ronda     bigint      NOT NULL REFERENCES ronda_lider (id_ronda) ON DELETE CASCADE,
    id_votante   bigint      NOT NULL REFERENCES usuario (id_usuario),
    id_candidato bigint      NOT NULL REFERENCES usuario (id_usuario),
    votado_en    timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (id_ronda, id_votante)
);

CREATE INDEX voto_lider_candidato_idx ON voto_lider (id_ronda, id_candidato);

COMMENT ON TABLE voto_lider IS 'Voto emitido por un integrante en una ronda de elección de líder (bloque 3).';
COMMENT ON COLUMN voto_lider.id_ronda IS 'Ronda en la que se emite el voto.';
COMMENT ON COLUMN voto_lider.id_votante IS 'Integrante que vota (un voto por ronda).';
COMMENT ON COLUMN voto_lider.id_candidato IS 'Integrante por quien se vota.';
COMMENT ON COLUMN voto_lider.votado_en IS 'Instante en que se registró el voto.';

ALTER TABLE proyecto
    ADD COLUMN equipos_mixtos         boolean     NOT NULL DEFAULT false,
    ADD COLUMN cierre_equipos         timestamptz NULL,
    ADD COLUMN horas_ronda            integer     NOT NULL DEFAULT 48
        CONSTRAINT proyecto_horas_ronda_ck CHECK (horas_ronda BETWEEN 1 AND 336),
    ADD COLUMN rondas_programadas_en  timestamptz NULL,
    ADD COLUMN recordatorio_cierre_en timestamptz NULL;

COMMENT ON COLUMN proyecto.equipos_mixtos IS 'Indica si los equipos pueden mezclar estudiantes de distintos cursos; inmutable tras crear.';
COMMENT ON COLUMN proyecto.cierre_equipos IS 'Instante de cierre de autoinscripción en equipos (bloque 2).';
COMMENT ON COLUMN proyecto.horas_ronda IS 'Duración en horas de cada ronda de votación de líder (entre 1 y 336).';
COMMENT ON COLUMN proyecto.rondas_programadas_en IS 'Marca del programador para no repetir la apertura programada de rondas (bloque 3).';
COMMENT ON COLUMN proyecto.recordatorio_cierre_en IS 'Marca del programador para no repetir el recordatorio de cierre de equipos (bloque 3).';

ALTER TABLE equipo
    ADD COLUMN id_curso bigint  NULL REFERENCES curso (id_curso),
    ADD COLUMN cupo     integer NULL CONSTRAINT equipo_cupo_ck CHECK (cupo IS NULL OR cupo > 0);

COMMENT ON COLUMN equipo.id_curso IS 'Curso del equipo cuando el proyecto no es mixto; lo valida el servicio (bloque 2).';
COMMENT ON COLUMN equipo.cupo IS 'Cupo máximo de integrantes para autoinscripción; NULL significa equipo armado por el docente, sin autoinscripción.';

DROP INDEX correo_habilitado_equipo_invitado_idx;
ALTER TABLE correo_habilitado DROP CONSTRAINT correo_habilitado_invitacion_ck;
ALTER TABLE correo_habilitado DROP COLUMN id_equipo_invitado;
ALTER TABLE correo_habilitado ADD COLUMN id_curso bigint NULL REFERENCES curso (id_curso) ON DELETE CASCADE;
ALTER TABLE correo_habilitado DROP CONSTRAINT correo_habilitado_proyecto_ck;
ALTER TABLE correo_habilitado ADD CONSTRAINT correo_habilitado_ambito_ck CHECK (
       (rol_plataforma = 'DOCENTE'    AND id_proyecto IS NULL     AND id_curso IS NULL)
    OR (rol_plataforma = 'MONITOR'    AND id_proyecto IS NOT NULL AND id_curso IS NULL)
    OR (rol_plataforma = 'ESTUDIANTE' AND id_proyecto IS NULL     AND id_curso IS NOT NULL));
ALTER TABLE correo_habilitado DROP CONSTRAINT correo_habilitado_uk;
ALTER TABLE correo_habilitado ADD CONSTRAINT correo_habilitado_uk UNIQUE NULLS NOT DISTINCT (email, id_proyecto, id_curso);
CREATE INDEX correo_habilitado_curso_idx ON correo_habilitado (id_curso) WHERE id_curso IS NOT NULL;

COMMENT ON TABLE correo_habilitado IS 'Estudiantes: por curso, los habilita su docente. Monitores: por proyecto. Docentes: sin proyecto ni curso, los habilita el administrador.';
COMMENT ON COLUMN correo_habilitado.id_curso IS 'Curso que habilita al estudiante; obligatorio solo para rol ESTUDIANTE.';
