-- V1: tablas de notificaciones del núcleo (plan §8.1 y §8.8; decisiones-tecnicas-java §3).
-- Nombre físico = nombre del diagrama en minúscula (Evento_Saliente -> evento_saliente).

-- Usuario mínimo. El bloque del dominio agrega las demás columnas con ALTER TABLE (no la recrea).
CREATE TABLE usuario (
    id_usuario       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    telegram_chat_id bigint NULL,
    CONSTRAINT usuario_telegram_chat_id_uk UNIQUE (telegram_chat_id),
    CONSTRAINT usuario_telegram_chat_id_privado_ck CHECK (telegram_chat_id > 0)
);
COMMENT ON COLUMN usuario.telegram_chat_id IS
    'Chat privado de Telegram vinculado (D5, D7). Dato personal (Ley 1581 de 2012): se borra al desvincular o cuando Telegram responde 403.';

-- Outbox (Evento_Saliente). Se inserta en la MISMA transacción que el cambio de negocio.
CREATE TABLE evento_saliente (
    id           uuid        PRIMARY KEY,
    tipo         text        NOT NULL,
    carga        jsonb       NOT NULL,
    creado_en    timestamptz NOT NULL DEFAULT now(),
    publicado_en timestamptz NULL,
    intentos     integer     NOT NULL DEFAULT 0,
    CONSTRAINT evento_saliente_tipo_ck CHECK (tipo IN (
        'tarea.ruta_critica.riesgo',
        'equipo.inactividad',
        'hito.enviado',
        'hito.evaluado',
        'tarea.reasignada',
        'tarea.correccion'
    )),
    CONSTRAINT evento_saliente_intentos_ck CHECK (intentos >= 0)
);
COMMENT ON TABLE evento_saliente IS
    'Outbox: eventos CloudEvents pendientes de publicar en uniproject.eventos. publicado_en se llena solo tras la confirmación de RabbitMQ.';

-- Índice parcial que usa el publicador (... WHERE publicado_en IS NULL ORDER BY creado_en ... FOR UPDATE SKIP LOCKED).
CREATE INDEX evento_saliente_pendientes_idx
    ON evento_saliente (creado_en)
    WHERE publicado_en IS NULL;

-- Códigos de vinculación de un solo uso (plan §8.8). Código: 24 bytes aleatorios en Base64 URL sin relleno = 32 caracteres.
CREATE TABLE codigo_vinculacion (
    codigo     varchar(32) PRIMARY KEY,
    usuario_id bigint      NOT NULL REFERENCES usuario (id_usuario) ON DELETE CASCADE,
    creado_en  timestamptz NOT NULL DEFAULT now(),
    vence_en   timestamptz NOT NULL,
    usado_en   timestamptz NULL,
    CONSTRAINT codigo_vinculacion_formato_ck CHECK (codigo ~ '^[A-Za-z0-9_-]{32}$'),
    CONSTRAINT codigo_vinculacion_vigencia_ck CHECK (vence_en > creado_en)
);
CREATE INDEX codigo_vinculacion_usuario_idx ON codigo_vinculacion (usuario_id);
